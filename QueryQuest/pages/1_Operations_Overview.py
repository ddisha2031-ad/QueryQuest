import streamlit as st, plotly.express as px
f=st.session_state["filtered"]()
st.header("Operations Overview")
if f.empty: st.warning("No tickets match the selected filters."); st.stop()
c1,c2,c3,c4,c5,c6=st.columns(6)
c1.metric("Total tickets",f"{len(f):,}")
c2.metric("Open backlog",f"{int(f.is_open.sum()):,}")
c3.metric("Resolved",f"{int(f.resolved_at.notna().sum()):,}")
c4.metric("Avg resolution (min)",f"{f.resolution_minutes.mean():,.0f}")
c5.metric("Avg CSAT",f"{f.satisfaction_score.mean():.2f}")
c6.metric("Reopened",f"{int(f.reopened_count.sum()):,}")
m=f.groupby(f.created_at.dt.to_period("M")).size().reset_index(name="tickets"); m["created_at"]=m["created_at"].astype(str)
st.plotly_chart(px.line(m,x="created_at",y="tickets",title="Monthly ticket volume",markers=True),use_container_width=True)
a,b=st.columns(2)
a.plotly_chart(px.pie(f,names="ticket_status",title="Ticket status distribution",hole=.45),use_container_width=True)
b.plotly_chart(px.bar(f["priority"].value_counts().reset_index(),x="priority",y="count",title="Tickets by priority"),use_container_width=True)
